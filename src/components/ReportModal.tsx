import React from 'react';
import { X, Download, Printer, ShieldAlert, ShieldCheck, AlertTriangle, FileCode, CheckCircle2 } from 'lucide-react';
import { DetectionResult } from '../types';

interface ReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  result: DetectionResult | null;
}

export const ReportModal: React.FC<ReportModalProps> = ({ isOpen, onClose, result }) => {
  if (!isOpen || !result) return null;

  const isDeepfake = result.overallVerdict === 'SYNTHETIC_DEEPFAKE';
  const isSpliced = result.overallVerdict === 'SPLICED_MANIPULATION';

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadJson = () => {
    const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(result, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', dataStr);
    downloadAnchor.setAttribute('download', `DEEPFAKE-REPORT-${result.metadata.name}-${Date.now()}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const handleDownloadHtml = () => {
    const htmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Cybersecurity Audio Forensic Report - ${result.metadata.name}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #0b0f19; color: #f1f5f9; padding: 40px; margin: 0; }
    .card { background: #111827; border: 1px solid #1f2937; border-radius: 12px; padding: 24px; margin-bottom: 24px; }
    h1 { color: #38bdf8; margin-top: 0; font-size: 24px; }
    h2 { color: #f8fafc; font-size: 18px; border-bottom: 1px solid #374151; padding-bottom: 8px; }
    .verdict { font-size: 22px; font-weight: bold; padding: 16px; border-radius: 8px; margin-bottom: 20px; }
    .deepfake { background: #450a0a; color: #f87171; border: 1px solid #ef4444; }
    .genuine { background: #022c22; color: #34d399; border: 1px solid #10b981; }
    .spliced { background: #451a03; color: #fbbf24; border: 1px solid #f59e0b; }
    table { width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 13px; }
    th, td { border: 1px solid #374151; padding: 10px; text-align: left; }
    th { background: #1f2937; color: #94a3b8; }
    .mono { font-family: monospace; }
  </style>
</head>
<body>
  <h1>CYBERSECURITY DEEPFAKE AUDIO FORENSIC REPORT</h1>
  <p>Generated by Deepfake Audio Detection SOC System | Timestamp: ${result.analyzedAt}</p>
  
  <div class="verdict ${isDeepfake ? 'deepfake' : isSpliced ? 'spliced' : 'genuine'}">
    CLASSIFICATION: ${result.overallVerdict.replace('_', ' ')} (AI Probability: ${(result.deepfakeProbability * 100).toFixed(1)}% | Confidence: ${(result.confidenceScore * 100).toFixed(1)}%)
  </div>

  <div class="card">
    <h2>Executive Intelligence Summary</h2>
    <p>${result.executiveSummary}</p>
    <p><strong>Suspected Technique:</strong> ${result.suspectedTechnique}</p>
    <p><strong>Associated Threat:</strong> ${result.threatVector}</p>
  </div>

  <div class="card">
    <h2>Audio File Specifications & Chain of Custody</h2>
    <p><strong>File Name:</strong> ${result.metadata.name}</p>
    <p><strong>Duration:</strong> ${result.metadata.duration}s | <strong>Sample Rate:</strong> ${result.metadata.sampleRate} Hz</p>
    <p><strong>SHA-256 Hash:</strong> <span class="mono">${result.metadata.sha256Hash}</span></p>
  </div>

  <div class="card">
    <h2>Temporal Segment Breakdown</h2>
    <table>
      <thead>
        <tr>
          <th>Segment</th>
          <th>Time Range</th>
          <th>Verdict</th>
          <th>AI Prob</th>
          <th>Identified Forensic Indicators</th>
        </tr>
      </thead>
      <tbody>
        ${result.segments.map(s => `
          <tr>
            <td class="mono">#${s.index + 1}</td>
            <td class="mono">${s.startTime}s - ${s.endTime}s</td>
            <td class="mono">${s.verdict}</td>
            <td class="mono">${(s.deepfakeProbability * 100).toFixed(1)}%</td>
            <td>${s.anomalyReasons.join(', ')}</td>
          </tr>
        `).join('')}
      </tbody>
    </table>
  </div>
</body>
</html>`;

    const blob = new Blob([htmlContent], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `FORENSIC-REPORT-${result.metadata.name}.html`;
    document.body.appendChild(a);
    a.click();
    a.remove();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md overflow-y-auto">
      <div className="relative w-full max-w-4xl bg-slate-900 border border-slate-800 rounded-2xl shadow-2xl p-6 flex flex-col gap-6 max-h-[92vh] overflow-y-auto print:max-h-none print:overflow-visible print:border-none print:p-0 print:bg-white print:text-black">
        {/* Header - Hidden on Print */}
        <div className="flex items-start justify-between border-b border-slate-800 pb-4 print:hidden">
          <div>
            <span className="text-xs font-mono text-cyan-400 font-bold uppercase tracking-wider block mb-1">
              Official Cyber Forensic Audit
            </span>
            <h2 className="text-xl font-bold text-white flex items-center gap-2">
              Audio Deepfake Forensic Incident Report
            </h2>
            <p className="text-xs text-slate-400 mt-0.5">
              Case ID: AUD-FOR-{result.metadata.sha256Hash.substring(0, 10).toUpperCase()} | Timestamp: {result.analyzedAt}
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold flex items-center gap-1.5 transition-colors cursor-pointer"
            >
              <Printer className="w-3.5 h-3.5" />
              Print / Save PDF
            </button>

            <button
              onClick={handleDownloadHtml}
              className="px-3 py-1.5 rounded-lg bg-cyan-500/20 hover:bg-cyan-500/30 text-cyan-300 border border-cyan-500/40 text-xs font-semibold flex items-center gap-1.5 transition-colors cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              Download HTML
            </button>

            <button
              onClick={handleDownloadJson}
              className="px-3 py-1.5 rounded-lg bg-indigo-500/20 hover:bg-indigo-500/30 text-indigo-300 border border-indigo-500/40 text-xs font-semibold flex items-center gap-1.5 transition-colors cursor-pointer"
            >
              <FileCode className="w-3.5 h-3.5" />
              Download JSON
            </button>

            <button
              onClick={onClose}
              className="p-1.5 text-slate-400 hover:text-white hover:bg-slate-800 rounded-lg transition-colors cursor-pointer ml-1"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* PRINTABLE REPORT BODY */}
        <div className="space-y-5 print:space-y-4">
          {/* Classification Banner */}
          <div
            className={`p-5 rounded-xl border flex items-center justify-between ${
              isDeepfake
                ? 'bg-rose-950/60 border-rose-500 text-rose-200'
                : isSpliced
                ? 'bg-amber-950/60 border-amber-500 text-amber-200'
                : 'bg-emerald-950/60 border-emerald-500 text-emerald-200'
            }`}
          >
            <div>
              <span className="text-[10px] font-mono uppercase tracking-wider block font-bold">
                FINAL FORENSIC CLASSIFICATION
              </span>
              <h3 className="text-xl font-bold font-mono mt-0.5">
                {result.overallVerdict.replace('_', ' ')}
              </h3>
              <p className="text-xs mt-1 opacity-90">
                Threat Classification Level: {result.riskLevel} | Synthesis Method: {result.suspectedTechnique}
              </p>
            </div>

            <div className="text-right font-mono">
              <span className="text-[10px] uppercase block opacity-75">Deepfake Probability</span>
              <span className="text-2xl font-bold">
                {(result.deepfakeProbability * 100).toFixed(1)}%
              </span>
            </div>
          </div>

          {/* Audio Technical Details */}
          <div className="bg-slate-950/80 border border-slate-800 rounded-xl p-4 text-xs font-mono">
            <h4 className="text-slate-200 font-bold mb-2">EVIDENCE METADATA</h4>
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
              <div>
                <span className="text-slate-500 block">File Name:</span>
                <span className="text-slate-200 font-semibold">{result.metadata.name}</span>
              </div>
              <div>
                <span className="text-slate-500 block">Duration:</span>
                <span className="text-slate-200 font-semibold">{result.metadata.duration}s</span>
              </div>
              <div>
                <span className="text-slate-500 block">Sample Rate:</span>
                <span className="text-slate-200 font-semibold">{result.metadata.sampleRate} Hz</span>
              </div>
              <div>
                <span className="text-slate-500 block">Format:</span>
                <span className="text-slate-200 font-semibold uppercase">{result.metadata.format}</span>
              </div>
            </div>
            <div className="mt-2 pt-2 border-t border-slate-800/80">
              <span className="text-slate-500 block">Cryptographic SHA-256 Checksum:</span>
              <span className="text-cyan-400 break-all">{result.metadata.sha256Hash}</span>
            </div>
          </div>

          {/* Executive Summary */}
          <div className="bg-slate-950/80 border border-slate-800 rounded-xl p-4 text-xs">
            <h4 className="text-slate-200 font-bold mb-1.5 font-mono">EXECUTIVE SUMMARY</h4>
            <p className="text-slate-300 leading-relaxed font-sans">{result.executiveSummary}</p>
          </div>

          {/* Segment Forensic Breakdown Table */}
          <div className="bg-slate-950/80 border border-slate-800 rounded-xl p-4">
            <h4 className="text-slate-200 font-bold mb-2 text-xs font-mono">
              TEMPORAL SEGMENT INVENTORY ({result.segments.length} SLICES)
            </h4>
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs font-mono border-collapse">
                <thead>
                  <tr className="border-b border-slate-800 text-slate-400">
                    <th className="py-1.5 px-2">#</th>
                    <th className="py-1.5 px-2">Time Range</th>
                    <th className="py-1.5 px-2">Verdict</th>
                    <th className="py-1.5 px-2">AI Probability</th>
                    <th className="py-1.5 px-2">Key Acoustic Markers</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-800/60">
                  {result.segments.map((seg) => (
                    <tr
                      key={seg.index}
                      className={seg.verdict === 'DEEPFAKE' ? 'bg-rose-950/20' : seg.verdict === 'SUSPICIOUS' ? 'bg-amber-950/20' : ''}
                    >
                      <td className="py-1.5 px-2 text-slate-400">{seg.index + 1}</td>
                      <td className="py-1.5 px-2 text-cyan-300">{seg.startTime}s - {seg.endTime}s</td>
                      <td className="py-1.5 px-2">
                        <span
                          className={`px-1.5 py-0.5 rounded text-[10px] font-bold ${
                            seg.verdict === 'DEEPFAKE'
                              ? 'text-rose-400 bg-rose-500/20'
                              : seg.verdict === 'SUSPICIOUS'
                              ? 'text-amber-400 bg-amber-500/20'
                              : 'text-emerald-400 bg-emerald-500/20'
                          }`}
                        >
                          {seg.verdict}
                        </span>
                      </td>
                      <td className="py-1.5 px-2 font-bold">{(seg.deepfakeProbability * 100).toFixed(1)}%</td>
                      <td className="py-1.5 px-2 text-slate-300 font-sans text-[11px]">
                        {seg.anomalyReasons.join('; ')}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          {/* Mitigation Actions */}
          <div className="bg-slate-950/80 border border-slate-800 rounded-xl p-4 text-xs">
            <h4 className="text-slate-200 font-bold mb-2 font-mono">INCIDENT MITIGATION &amp; PLAYBOOK</h4>
            <div className="space-y-1 text-slate-300">
              {result.mitigationRecommendations.map((rec, i) => (
                <div key={i} className="flex items-start gap-1.5">
                  <span className="text-cyan-400 font-mono font-bold">•</span>
                  <span>{rec}</span>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="flex items-center justify-between border-t border-slate-800 pt-3 text-xs text-slate-500 font-mono print:hidden">
          <span>Digital Forensic Hash Verified: SHA-256</span>
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 transition-colors cursor-pointer"
          >
            Close Report
          </button>
        </div>
      </div>
    </div>
  );
};
